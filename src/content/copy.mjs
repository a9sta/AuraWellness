/** 치우침 정도를 말로 */
export function tiltWord(t) {
  if (t < 8) return '네 자락에 거의 고르게 퍼져 있습니다';
  if (t < 18) return '한쪽이 조금 두툼한 정도입니다';
  if (t < 30) return '한 자락으로 눈에 띄게 몰려 있습니다';
  if (t < 48) return '땅이 한쪽에 크게 쏠려 있습니다';
  return '한 자락이 거의 전부를 가져간 모양입니다';
}
/** 무게가 선 자리가 가운데에서 얼마나 밀렸나 */
export function offWord(m) {
  if (m < 40) return '무게가 네모 한가운데에 거의 그대로 서 있습니다';
  if (m < 150) return '무게 중심이 가운데에서 조금 비켜나 있습니다';
  if (m < 400) return '무게 중심이 한쪽으로 분명히 밀렸습니다';
  if (m < 1200) return '무게 중심이 가운데에서 멀찍이 떨어져 있습니다';
  return '무게 중심과 네모 한가운데가 아주 멀리 떨어져 있습니다';
}
/** 북쪽 몫을 말로 */
export function northWord(n) {
  if (n >= 70) return '거의 북쪽에만 땅이 있습니다';
  if (n >= 58) return '북쪽이 눈에 띄게 넓습니다';
  if (n >= 43) return '위아래가 비슷하게 나뉩니다';
  if (n >= 31) return '남쪽이 눈에 띄게 넓습니다';
  return '거의 남쪽에만 땅이 있습니다';
}
/** 동쪽 몫을 말로 */
export function eastWord(e) {
  if (e >= 70) return '동쪽 끝에 거의 다 몰려 있습니다';
  if (e >= 58) return '동쪽이 더 넓습니다';
  if (e >= 43) return '좌우가 엇비슷합니다';
  if (e >= 31) return '서쪽이 더 넓습니다';
  return '서쪽 끝에 거의 다 몰려 있습니다';
}
